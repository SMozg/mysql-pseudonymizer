"""Блок Д'' -- ПЕРЕСТАНОВКА значений внутри класса (Р-123, идея владельца 07.09).

⛔ ЗАЧЕМ ОТДЕЛЬНЫЙ ПОСТАВЩИК, А НЕ ЕЩЁ ОДНА ФОРМУЛИРОВКА ЗАПРОСА. Пять замеров
07.09 на классе фамилий показали стену, которую не двигает ни температура, ни
число вариантов, ни страновой тег: модель на 599 фамилий предлагает **75**
таких, которых в базе ещё нет, а нужно 599. Её собственные слова из ответа:
"this task requires generating hundreds of unique surname alternatives ...
I recommend using a programmatic approach with a name database". Для сравнения,
на именах она даёт 952 новых -- потому имена и лечатся моделью, а фамилии нет.

⛔ ЧТО ДЕЛАЕТ. Меняет значения класса МЕСТАМИ: перестановка без неподвижных
точек внутри группы. Группа у человека -- одна длина, у города -- одна страна. Приём известный -- data swapping из
статистического раскрытия данных. Он даёт то, чего модель дать не может:
    · разнообразие 100 % ПО ПОСТРОЕНИЮ -- сколько различных было, столько и стало;
    · распределение длин совпадает с исходным до буквы;
    · склеек ноль -- перестановка взаимно однозначна;
    · вызовов сети ноль.

⛔ ЦЕНА, КОТОРУЮ НЕЛЬЗЯ ПРЯТАТЬ. Набор значений в базе остаётся ПРЕЖНИМ: рвётся
связь «эта строка -- этот человек», но факт «человек с такой фамилией в базе
есть» сохраняется. Поэтому критерий 1(в) -- совпадение с ЧУЖИМ исходным -- по
этому классу равен 100 % ПО ПОСТРОЕНИЮ, и это диагностика с числом, а не отказ
(Р-93). Для базы, где чувствительно само присутствие значения, приём не годится;
место этой оговорки -- раздел «Пределы» README, и она там есть.

📌 ОСТАТОК ОТДАЁТСЯ МОДЕЛИ. Значение, у которого нет пары той же длины
(в Sakila таких ровно два: 'VU' -- единственное в 2 буквы, 'WESTMORELAND' --
единственное в 12), уходит в поставщика-запасного. ⛔ Так ЛЛМ остаётся в работе
и на этом классе, а не вытесняется: предмет проверки задания -- умение работать
с моделью, и подменять её целиком там, где она справляется, незачем.
"""
from __future__ import annotations

import dataclasses
import hashlib
import hmac
import os
import random
import unicodedata
from collections import defaultdict

from ..models import ProviderResponse, ResponseItem, Usage

DEFAULT_HANDLES = frozenset({"КЗ-1", "КЗ-2", "КЗ-3"})

#: ⛔ ПОЧЕМУ НЕ СДВИГ ПО КРУГУ. Сдвиг сохраняет ПОРЯДОК: отсортированный список
#: исходных значений отображается в отсортированный список замен, и вся перестановка
#: описывается одним числом. Из n! возможных перестановок остаётся n-1, а ОДНА
#: известная пара «было -> стало» вскрывает группу целиком. Находка владельца 08.09.
#: 📌 Вместо сдвига -- СЛУЧАЙНАЯ перестановка без неподвижных точек (алгоритм Саттоло:
#: (n-1)! вариантов, ровно один цикл, неподвижных точек нет ПО ПОСТРОЕНИЮ), а зерно
#: берётся не из открытого seed, а из HMAC на КЛЮЧЕ ШИФРОВАНИЯ СЛОВАРЯ. Логика цельная:
#: кто держит ключ -- тот и обращает замену, что словарём, что перестановкой.
#: ⛔ Направление круга («имя в одну сторону, фамилия в другую») этим ОТМЕНЯЕТСЯ:
#: независимые перестановки не связаны никак, и подпорка становится бессмысленной.
#: Вместе с ней уходит оговорка про чётные группы, где направление ничего не меняло.

#: ⛔ ЧЕМ ГРУППИРОВАТЬ ЗНАЧЕНИЯ ПЕРЕД СДВИГОМ -- РАЗНОЕ У ЧЕЛОВЕКА И У ГОРОДА.
#: Человеку группа задана ДЛИНОЙ: замена обязана уместиться в колонку и не выглядеть
#: чужеродно. Городу -- СТРАНОЙ: требование Р-1 «замена есть настоящий город ТОЙ ЖЕ
#: страны» сильнее любой длины (самое длинное название 26 символов при лимите 50,
#: длина не решает ничего). 📌 Побочно это разводит одноимённые города разных стран
#: само собой: два London лежат в РАЗНЫХ группах и встретиться не могут -- заявленный
#: разрыв сквозной замены (Р-45) держится построением, а не оговоркой.
_GROUP_BY_COUNTRY = frozenset({"КЗ-3"})

#: ⛔ РОВНО ОДИН кандидат на строку. Несколько сдвигов ломали биекцию: фильтр
#: вправе взять второго кандидата (предпочтение по чужому исходному, а на
#: последней попытке -- и предохранитель склейки), и тогда двое приходят к одному
#: значению -- судья 07.09 нашёл `Stockport` и `York`, оба ушедшие в `Southport`,
#: и `London`, исчезнувший из базы. Гарантия «склеек ноль» держится только тогда,
#: когда выбор один. 📌 На повторе группа пересобирается заново, запас не нужен.

class ShuffleProvider:
    """Перестановка значений класса; остаток -- запасному поставщику."""

    def __init__(self, seed: int, *, handles=None, fallback=None):
        self.seed = seed
        self.name = "shuffle"
        self.handles = frozenset(handles) if handles is not None else DEFAULT_HANDLES
        #: ⛔ Запасной поставщик (обычно модель) -- НЕ обязателен: без него
        #: одиночки останутся без ответа, это отказ и повтор, а не тихий пропуск.
        self.fallback = fallback
        self._key = None

    def supply(self, batch) -> ProviderResponse:
        by_country = batch.value_class in _GROUP_BY_COUNTRY
        groups = defaultdict(list)
        for item in batch.items:
            if by_country:
                # ⛔ Страна берётся из `fmt` -- её кладёт туда охват значения (Р-45 А:
                # охват города это пара «город, страна»). Нет страны -- нет группы:
                # значение уходит запасному поставщику, а не в чужую страну.
                key = (item.fmt or {}).get("country_id")
                if key is None:
                    key = ("нет страны", id(item))
            else:
                key = len(str(item.old_value))
            groups[key].append(item)

        answers = []
        orphans = []
        seed = getattr(batch, "seed", None)
        if seed is None:
            seed = self.seed
        for key in sorted(groups, key=lambda k: str(k)):
            group = groups[key]
            if len(group) < 2:
                # Группа из одного значения -- переставлять не с чем.
                orphans.extend(group)
                continue
            paired, refused = self._permute(group, seed, batch.value_class, key,
                                            self._key_material())
            answers.extend(paired)
            orphans.extend(refused)

        usage_calls, usage_tokens = 1, None
        if orphans and self.fallback is not None:
            sub = dataclasses.replace(batch, items=tuple(orphans))
            spare = self.fallback.supply(sub)
            answers.extend(spare.items)
            usage_calls += spare.usage.calls
            usage_tokens = spare.usage.tokens

        return ProviderResponse(
            items=tuple(answers),
            usage=Usage(calls=usage_calls, values=len(answers),
                        refusals=0, tokens=usage_tokens),
        )

    def _key_material(self) -> bytes:
        """Ключ шифрования словаря -- он же зерно перестановки.

        ⛔ Читается ЛЕНИВО, при первом обращении: сборка поставщиков не должна
        падать там, где ключ ещё не нужен. Нет ключа -- перестановка строится на
        одном seed: она остаётся случайной и без неподвижных точек, но становится
        УГАДЫВАЕМОЙ, если seed известен. Это честный запасной путь, а не тихая
        подмена: без ключа не откроется и словарь, так что прогон всё равно встанет
        предпусковым гейтом с названным именем переменной.
        """
        if self._key is None:
            self._key = os.environ.get("SANIT_KEY", "").encode("utf-8")
        return self._key

    @staticmethod
    def _permute(group, seed: int, value_class: str, group_key, key_material: bytes):
        """Случайная перестановка группы БЕЗ неподвижных точек (алгоритм Саттоло).

        ⛔ ПОЧЕМУ САТТОЛО, А НЕ ОБЫЧНАЯ ТАСОВКА: он даёт перестановку из ОДНОГО цикла,
        а значит неподвижных точек нет ПО ПОСТРОЕНИЮ -- значение не может достаться
        самому себе, и жёсткой проверке «равно своему исходному» здесь нечего ловить.
        Обычная тасовка оставила бы неподвижные точки, и их пришлось бы чинить
        постобработкой, то есть надеяться вместо гарантии.

        ⛔ ЗЕРНО -- НА КЛЮЧЕ, А НЕ НА ОТКРЫТОМ seed. Иначе перестановку восстанавливает
        любой, кто знает seed и набор значений (а набор в базе не меняется -- см.
        «Пределы»). HMAC связывает зерно с ключом шифрования словаря: кто держит ключ,
        тот и обращает замену, что словарём, что перестановкой.
        📌 Воспроизводимость держится: тот же ключ и тот же seed дают
        ту же перестановку. Порядок -- сортировка значений, а не порядок прихода строк.

        Возвращает (готовые ответы, отбитые элементы). ⛔ Отбитые -- это те, кому
        перестановка не смогла дать годного значения: длиннее лимита колонки или
        совпадает со своим исходным после нормализации (разный регистр, диакритика).
        Они уходят ЗАПАСНОМУ поставщику, а не остаются без ответа: решение владельца
        08.09 -- «если будет эхо, отдаём в ЛЛМ на замену».
        """
        ordered = sorted(group, key=lambda it: str(it.old_value))
        n = len(ordered)
        material = b"|".join((key_material, str(seed).encode("utf-8"),
                              value_class.encode("utf-8"), str(group_key).encode("utf-8")))
        digest = hmac.new(key_material or b"no-key", material, hashlib.sha256).digest()
        rng = random.Random(int.from_bytes(digest, "big"))

        targets = list(range(n))
        for i in range(n - 1, 0, -1):          # ⛔ Саттоло: randrange(i), НЕ randrange(i+1)
            j = rng.randrange(i)
            targets[i], targets[j] = targets[j], targets[i]

        out, refused = [], []
        for idx, item in enumerate(ordered):
            value = str(ordered[targets[idx]].old_value)
            limit = item.length_limit
            too_long = limit is not None and len(value) > limit
            same = _norm(value) == _norm(str(item.old_value))
            if too_long or same:
                refused.append(item)
                continue
            out.append(ResponseItem(key=item.key, new_value=(value,)))
        return out, refused


def _norm(value: str) -> str:
    """Та же нормализация, что у фильтра замен: без регистра и без диакритики.
    ⛔ Иначе «эхо после нормализации» проскочило бы мимо и всплыло уже отказом
    в блоке Г -- с отказом, но без запасного поставщика."""
    decomposed = unicodedata.normalize("NFD", value)
    return "".join(ch for ch in decomposed if not unicodedata.combining(ch)).upper()
