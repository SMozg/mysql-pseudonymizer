-- Права пользователя приложения на рабочие схемы инструмента.
-- Выполняется третьим по алфавиту, после схемы (01-) и данных (02-): образ MySQL
-- прогоняет файлы из /docker-entrypoint-initdb.d по порядку имён.
--
-- Инструменту мало читать sakila — он ещё СОЗДАЁТ схемы: рабочую копию, снимок "до",
-- приёмник обратного прогона и временную схему приёмки, все с именами вида sanit_*.
-- Права выдаются шаблоном на все такие схемы разом, подчёркивание экранировано —
-- иначе шаблон "sanit_%" совпал бы и с посторонней схемой вроде "sanitXYZ".
--
-- ОГРАНИЧЕНИЕ: имя пользователя ниже захардкожено ('sakila_app', см. .env.example) —
-- SQL-файлы в /docker-entrypoint-initdb.d образ MySQL выполняет буквально, без
-- подстановки переменных окружения (интерполяция ${...} доступна только *.sh-скриптам
-- в том же каталоге, не *.sql). Если MYSQL_USER в .env сменят на другое имя, этот файл
-- нужно поправить вручную вместе с ним.

GRANT ALL PRIVILEGES ON `sanit\_%`.* TO 'sakila_app'@'%';
FLUSH PRIVILEGES;
